package com.example.wheretogo.ui.auth.validation

/**
 * Причина, по которой значение поля формы не принято.
 * null вместо ошибки означает «значение корректно».
 *
 * ## Зачем нужен
 * Это общий «словарь» ошибок для валидаторов экранов входа и регистрации.
 * Валидатор НЕ возвращает готовый текст для пользователя — он возвращает только
 * причину (enum). Благодаря этому логику проверки можно тестировать юнит-тестами
 * без Android и без строковых ресурсов, а текст подбирать отдельно на уровне UI.
 *
 * ## Где используется
 * - [LoginValidator] (файл LoginValidator.kt) — только [EMPTY].
 * - [RegistrationValidator] (файл RegistrationValidator.kt) — все значения.
 *
 * ## Что означает каждое значение
 * - [EMPTY] — поле пустое (или состоит только из пробелов, если поле обрезается).
 * - [TOO_SHORT] — значение короче минимально допустимого (имя < NAME_MIN, пароль < PASSWORD_MIN).
 * - [TOO_LONG] — значение длиннее максимально допустимого (имя > NAME_MAX).
 * - [INVALID_FORMAT] — не подходит по формату (телефон, почта).
 * - [WEAK_PASSWORD] — пароль достаточной длины, но нет букв или цифр.
 * - [MISMATCH] — подтверждение пароля не совпадает с паролем.
 *
 * ## Важно
 * Сейчас [LoginViewModel] и [RegisterViewModel] (пакет ui.auth) этот enum и
 * валидаторы НЕ используют: у них свои собственные проверки со своими текстами и
 * правилами (см. комментарии в этих файлах). Пакет validation пока «заготовка»,
 * к которой ViewModel'и можно перевести: ошибка из валидатора → текст для UI.
 */
enum class FieldError { EMPTY, TOO_SHORT, TOO_LONG, INVALID_FORMAT, WEAK_PASSWORD, MISMATCH }