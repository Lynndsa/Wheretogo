package com.example.wheretogo.ui.auth.validation

/**
 * Результат проверки формы входа: по одному полю на каждое поле формы.
 * null в поле означает «это поле корректно», иначе там причина ошибки [FieldError]
 * (см. FieldError.kt).
 *
 * Поля соответствуют полям экрана входа (LoginActivity.kt, функция LoginWindow):
 * - [name]     — поле «Имя»;
 * - [password] — поле «Пароль».
 */
data class LoginErrors(val name: FieldError? = null, val password: FieldError? = null) {
    /** true, если ошибок нет ни в одном поле — тогда можно отправлять запрос на сервер. */
    val isValid: Boolean get() = name == null && password == null
}

/**
 * Локальная (клиентская) проверка формы входа ДО обращения к серверу.
 * Это чистая Kotlin-логика без зависимостей от Android, поэтому легко покрывается юнит-тестами.
 *
 * Правила:
 * L1 Имя: не пустое и не состоит только из пробелов.
 * L2 Пароль: не пустой. Пароль не обрезается: строка из пробелов — допустимый ввод.
 *
 * Почему имя проверяется через isBlank(), а пароль через isEmpty():
 * имя — это «человеческое» значение, пробелы по краям там ничего не значат;
 * пароль же может содержать любые символы, включая пробелы, и менять его нельзя.
 *
 * Связь с остальным кодом:
 * - Здесь проверяется только «заполнено ли поле». Существует ли пользователь и верен ли
 *   пароль, решает сервер (ответы LOGIN_NOT_EXIST / PASSWORD_EXIST разбираются в
 *   LoginViewModel.kt).
 * - ВНИМАНИЕ: сейчас LoginViewModel этот объект не вызывает, а проверяет поля сам, причём
 *   для пароля использует isBlank() (строка из пробелов там считается пустой), что
 *   расходится с правилом L2. При переходе на LoginValidator поведение изменится.
 */
object LoginValidator {
    /**
     * Проверяет введённые значения и возвращает [LoginErrors].
     * @param name     значение поля «Имя» как введено пользователем
     * @param password значение поля «Пароль» как введено пользователем (без обрезки)
     */
    fun validate(name: String, password: String) = LoginErrors(
        name = if (name.isBlank()) FieldError.EMPTY else null,
        password = if (password.isEmpty()) FieldError.EMPTY else null
    )
}